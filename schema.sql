-- Schema SQLite derivato dallo script Oracle del progetto di Basi di Dati (date in formato ISO)
CREATE TABLE MANAGER (ID TEXT PRIMARY KEY, NOME TEXT NOT NULL, COGNOME TEXT NOT NULL, ETA INT NOT NULL CHECK (ETA > 18));
CREATE TABLE DIPENDENTI (ID TEXT PRIMARY KEY, NOME TEXT NOT NULL, COGNOME TEXT NOT NULL, ETA INT NOT NULL CHECK (ETA > 18),
  IBAN TEXT NOT NULL, LICENZA INT, BREVETTO INT, DATA_ASSUNZIONE TEXT NOT NULL, DISCRIMINATORE INT NOT NULL,
  MANAGER TEXT REFERENCES MANAGER(ID));
CREATE TABLE ARTICOLI (CODICE INT PRIMARY KEY, NOME TEXT NOT NULL, QUANT_DISPONIBILE INT NOT NULL CHECK (QUANT_DISPONIBILE >= 1),
  TAGLIA TEXT NOT NULL, PREZZO INT);
CREATE TABLE ABBONAMENTI (ID TEXT PRIMARY KEY, DURATA TEXT, COSTO_EUR INT NOT NULL, TIPOLOGIA TEXT NOT NULL);
CREATE TABLE UTENTI (ID TEXT PRIMARY KEY, NOME TEXT NOT NULL, COGNOME TEXT NOT NULL, EMAIL TEXT NOT NULL, VIA TEXT NOT NULL,
  CAP INT NOT NULL, CITTA TEXT NOT NULL, NUM_TELEFONO INT NOT NULL, ETA INT NOT NULL CHECK (ETA >= 16),
  ABBONAMENTO TEXT REFERENCES ABBONAMENTI(ID), DIPENDENTE TEXT REFERENCES DIPENDENTI(ID));
CREATE TABLE ACQUISTI (UTENTE TEXT REFERENCES UTENTI(ID), ARTICOLO INT REFERENCES ARTICOLI(CODICE),
  DATA TEXT NOT NULL, QUANTITA INT NOT NULL CHECK (QUANTITA >= 1));
CREATE TABLE PACCHETTI_FISIOTERAPIA (ID TEXT PRIMARY KEY, TIPOLOGIA TEXT NOT NULL, COSTO INT NOT NULL);
CREATE TABLE PRENOTA (UTENTE TEXT REFERENCES UTENTI(ID), PACCHETTO_FISIO TEXT REFERENCES PACCHETTI_FISIOTERAPIA(ID));
CREATE TABLE CONSULENZA_FISIO (UTENTE TEXT REFERENCES UTENTI(ID), DIPENDENTE TEXT REFERENCES DIPENDENTI(ID), DATA TEXT, ORA TEXT);
CREATE TABLE RICHIEDERE_PERSONAL (UTENTE TEXT REFERENCES UTENTI(ID), DIPENDENTE TEXT REFERENCES DIPENDENTI(ID),
  DATA TEXT, ORA_INIZIO TEXT, ORA_FINE TEXT, COSTO_EUR INT);

